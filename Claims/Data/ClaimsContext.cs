using Claims.Models;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ValueGeneration;
using MongoDB.EntityFrameworkCore.Extensions;

namespace Claims.Data
{
    public class ClaimsContext : DbContext
    {

        public DbSet<Claim> Claims { get; init; }
        public DbSet<Cover>  Covers { get; init; }

        public ClaimsContext(DbContextOptions options)
            : base(options)
        {
        }

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            base.OnModelCreating(modelBuilder);
            // Ids are generated by EF Core when an entity is added, as Guid strings.
            modelBuilder.Entity<Claim>().ToCollection("claims")
                .Property(claim => claim.Id).HasValueGenerator<StringValueGenerator>();
            modelBuilder.Entity<Cover>().ToCollection("covers")
                .Property(cover => cover.Id).HasValueGenerator<StringValueGenerator>();
        }
    }
}
